use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::core::CoreKind;

/// Parameters shared by the three bootstrap config generators.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BootstrapOptions {
    /// Local inbound port (mixed / socks, depending on the core).
    pub listen_port: u16,
    /// Local controller / API port where the core exposes one.
    pub api_port: u16,
    pub log_level: String,
}

impl Default for BootstrapOptions {
    fn default() -> Self {
        Self {
            listen_port: 7890,
            api_port: 9090,
            log_level: "info".to_string(),
        }
    }
}

/// Minimal, *direct-only* configuration for each core.
///
/// Scope boundary — this is **not** the Config Compiler from Phase 3. It exists
/// so that Phase 1 can prove the lifecycle story end to end ("three cores can be
/// started and stopped reliably") without pulling the Unified Profile forward.
/// Nothing here consumes a `Profile`; the compiler will replace these functions
/// wholesale in Phase 3 and must not grow out of them.
pub fn render(kind: CoreKind, options: &BootstrapOptions) -> String {
    match kind {
        CoreKind::Mihomo => mihomo_yaml(options),
        CoreKind::SingBox => singbox_json(options),
        CoreKind::Xray => xray_json(options),
    }
}

pub fn config_file_name(kind: CoreKind) -> &'static str {
    match kind {
        CoreKind::Mihomo => "bootstrap.yaml",
        CoreKind::SingBox => "bootstrap.json",
        CoreKind::Xray => "bootstrap.json",
    }
}

/// Write the bootstrap config for a core and return its path.
pub fn config_path_for(config_dir: &Path, kind: CoreKind) -> PathBuf {
    config_dir.join(config_file_name(kind))
}

fn mihomo_yaml(options: &BootstrapOptions) -> String {
    format!(
        "# Generated by TriProxy (Phase 1 bootstrap config — not a compiled profile).\n\
         mixed-port: {port}\n\
         allow-lan: false\n\
         bind-address: 127.0.0.1\n\
         mode: rule\n\
         log-level: {level}\n\
         ipv6: false\n\
         external-controller: 127.0.0.1:{api}\n\
         proxies: []\n\
         proxy-groups: []\n\
         rules:\n\
         \x20 - MATCH,DIRECT\n",
        port = options.listen_port,
        level = options.log_level,
        api = options.api_port,
    )
}

fn singbox_json(options: &BootstrapOptions) -> String {
    let config = serde_json::json!({
        "log": {
            "level": options.log_level,
            "timestamp": true
        },
        "inbounds": [{
            "type": "mixed",
            "tag": "mixed-in",
            "listen": "127.0.0.1",
            "listen_port": options.listen_port
        }],
        "outbounds": [{
            "type": "direct",
            "tag": "direct"
        }],
        "experimental": {
            "clash_api": {
                "external_controller": format!("127.0.0.1:{}", options.api_port)
            }
        }
    });
    let mut text = serde_json::to_string_pretty(&config).unwrap_or_default();
    text.push('\n');
    text
}

fn xray_json(options: &BootstrapOptions) -> String {
    // Xray has no "mixed" inbound: socks and http are declared separately, so the
    // http inbound takes listen_port + 1.
    let config = serde_json::json!({
        "log": {
            "loglevel": xray_log_level(&options.log_level)
        },
        "inbounds": [
            {
                "tag": "socks-in",
                "listen": "127.0.0.1",
                "port": options.listen_port,
                "protocol": "socks",
                "settings": { "udp": true }
            },
            {
                "tag": "http-in",
                "listen": "127.0.0.1",
                "port": options.listen_port.saturating_add(1),
                "protocol": "http"
            }
        ],
        "outbounds": [
            { "tag": "direct", "protocol": "freedom" }
        ]
    });
    let mut text = serde_json::to_string_pretty(&config).unwrap_or_default();
    text.push('\n');
    text
}

/// Xray only accepts debug / info / warning / error / none.
fn xray_log_level(level: &str) -> &'static str {
    match level.to_ascii_lowercase().as_str() {
        "debug" | "trace" => "debug",
        "warn" | "warning" => "warning",
        "error" | "fatal" => "error",
        "none" => "none",
        _ => "info",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn singbox_and_xray_bootstrap_are_valid_json() {
        let options = BootstrapOptions::default();
        for kind in [CoreKind::SingBox, CoreKind::Xray] {
            let text = render(kind, &options);
            serde_json::from_str::<serde_json::Value>(&text)
                .unwrap_or_else(|e| panic!("{kind:?} produced invalid json: {e}"));
        }
    }

    #[test]
    fn xray_http_inbound_avoids_port_collision() {
        let options = BootstrapOptions {
            listen_port: 7890,
            ..Default::default()
        };
        let parsed: serde_json::Value =
            serde_json::from_str(&render(CoreKind::Xray, &options)).unwrap();
        let ports: Vec<u64> = parsed["inbounds"]
            .as_array()
            .unwrap()
            .iter()
            .map(|inbound| inbound["port"].as_u64().unwrap())
            .collect();
        assert_eq!(ports, vec![7890, 7891]);
    }

    #[test]
    fn mihomo_bootstrap_pins_loopback_and_direct_rule() {
        let text = render(CoreKind::Mihomo, &BootstrapOptions::default());
        assert!(text.contains("bind-address: 127.0.0.1"));
        assert!(text.contains("mixed-port: 7890"));
        assert!(text.contains("MATCH,DIRECT"));
    }
}
